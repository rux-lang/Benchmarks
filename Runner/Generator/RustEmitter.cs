using System.Text;

namespace Runner.Generator;

/// <summary>One crate: src/main.rs, src/common.rs, and src/groupN/mod.rs with one file per module.</summary>
sealed class RustEmitter : Emitter
{
    public override string Folder => "Rust";

    protected override string Literal(ulong value) => Number(value);
    protected override string Rotl(string value, int amount) => $"rotl({value}, {amount})";
    protected override string Declare(Declare d) => $"let {(d.Mutable ? "mut " : "")}{d.Name}: u64 = {Expression(d.Value)};";
    protected override string IfHead(Compare c) => $"if {Condition(c)}";
    protected override string LoopHead(Loop loop, bool variableUsed) =>
        $"for {(variableUsed ? loop.Variable : "_")} in 0..{loop.Count}u64";
    protected override string ReturnLine(Return r, bool last) => last ? Expression(r.Value) : base.ReturnLine(r, last);

    /// <summary>+, - and * wrap explicitly; the other operators cannot overflow.</summary>
    protected override string BinaryText(Binary b)
    {
        string? method = b.Op switch { '+' => "wrapping_add", '-' => "wrapping_sub", '*' => "wrapping_mul", _ => null };
        if (method == null)
            return $"{Operand(b.Left, NeedsParentheses(b.Left))} {b.Op} {Operand(b.Right, NeedsParentheses(b.Right))}";
        string receiver = b.Left switch
        {
            Lit l => Number(l.Value) + "u64",
            _ when NeedsParentheses(b.Left) => $"({Expression(b.Left)})",
            _ => Expression(b.Left),
        };
        return $"{receiver}.{method}({Expression(b.Right)})";
    }

    /// <summary>Wrapping calls bind like a method call; infix operators, shifts and remainders need parentheses.</summary>
    static bool NeedsParentheses(Expr e) => e is ShiftBy or Modulo || e is Binary { Op: not ('+' or '-' or '*') };

    /// <summary>The module's path below its group: its file, then its inline module when the file holds several.</summary>
    static string InGroup(ModuleSpec m) => (m.SharesFile ? m.File.ToLowerInvariant() + "::" : "") + m.Name.ToLowerInvariant();

    static string ModulePath(ModuleSpec m) => $"crate::group{m.Group}::{InGroup(m)}";

    public override string ModuleFile(ModuleSpec m) => $"src/group{m.Group}/{m.File.ToLowerInvariant()}.rs";

    public override IEnumerable<SourceFile> Emit(ProjectSpec project)
    {
        string crate = project.Name.ToLowerInvariant();
        yield return new SourceFile("Cargo.toml", $"""
            [package]
            name = "{crate}"
            version = "0.1.0"
            edition = "2024"
            publish = false

            [profile.release]
            opt-level = 3
            debug = false
            strip = "symbols"
            incremental = false
            lto = false

            """);
        yield return new SourceFile("Cargo.lock", $"""
            # This file is automatically @generated by Cargo.
            # It is not intended for manual editing.
            version = 4

            [[package]]
            name = "{crate}"
            version = "0.1.0"

            """);
        yield return new SourceFile("src/common.rs", $$"""
            //! Common: helpers shared by every module: a SplitMix64 generator, rotation and FNV-1a mixing.
            //! {{Banner}}
            #![allow(dead_code)]

            pub struct Rng {
                state: u64,
            }

            impl Rng {
                pub fn new(seed: u64) -> Self {
                    Rng { state: seed }
                }

                pub fn next(&mut self) -> u64 {
                    self.state = self.state.wrapping_add(0x9E3779B97F4A7C15);
                    let mut z = self.state;
                    z = (z ^ (z >> 30)).wrapping_mul(0xBF58476D1CE4E5B9);
                    z = (z ^ (z >> 27)).wrapping_mul(0x94D049BB133111EB);
                    z ^ (z >> 31)
                }
            }

            pub fn rotl(value: u64, amount: u32) -> u64 {
                value.rotate_left(amount)
            }

            pub fn fnv(hash: u64, value: u64) -> u64 {
                (hash ^ value).wrapping_mul(0x100000001B3)
            }

            """);
        var main = new StringBuilder();
        main.AppendLine($"//! {project.Name}: runs every module once and prints an FNV-1a hash of their results.");
        main.AppendLine($"//! {Banner}");
        main.AppendLine("mod common;");
        foreach (int group in project.Groups)
            main.AppendLine($"mod group{group};");
        main.AppendLine();
        main.AppendLine("fn main() {");
        main.AppendLine("    let mut hash = 0xCBF29CE484222325u64;");
        foreach (int group in project.Groups)
            main.AppendLine($"    hash = group{group}::run_all(hash);");
        main.AppendLine("    println!(\"{hash:016x}\");");
        main.AppendLine("}");
        yield return new SourceFile("src/main.rs", main.ToString());
        foreach (int group in project.Groups)
        {
            var mods = new StringBuilder($"//! Group {group}: its modules, and a runner that runs them in order.\n//! {Banner}\n");
            foreach (string file in project.InGroup(group).Select(m => m.File).Distinct())
                mods.AppendLine($"pub mod {file.ToLowerInvariant()};");
            mods.AppendLine();
            mods.AppendLine("pub fn run_all(hash: u64) -> u64 {");
            mods.AppendLine("    let mut result = hash;");
            foreach (var m in project.InGroup(group))
                mods.AppendLine($"    result = crate::common::fnv(result, {InGroup(m)}::run({m.Index}));");
            mods.AppendLine("    result");
            mods.AppendLine("}");
            yield return new SourceFile($"src/group{group}/mod.rs", mods.ToString());
        }
        foreach (var file in project.Files)
        {
            var modules = file.ToList();
            string content = modules.Count == 1
                ? Comment("//!", modules[0]) + Module(modules[0])
                : FileComment("//!", modules) + string.Join('\n', modules.Select(m =>
                    ModuleComment("//", m) + $"pub mod {m.Name.ToLowerInvariant()} {{\n" + Indent(Module(m).TrimEnd(), 1) + "\n}\n"));
            yield return new SourceFile(ModuleFile(modules[0]), content);
        }
    }

    /// <summary>One module's items: a file of its own, or the body of an inline module.</summary>
    string Module(ModuleSpec m)
    {
        var file = new StringBuilder();
        var common = new List<string> { "Rng" };
        if (m.UsesFnv)
            common.Insert(0, "fnv");
        if (m.UsesRotl)
            common.Insert(m.UsesFnv ? 1 : 0, "rotl");
        file.AppendLine($"use crate::common::{(common.Count == 1 ? common[0] : "{" + string.Join(", ", common) + "}")};");
        if (m.Kind == Kind.Tally)
            file.AppendLine("use std::collections::HashMap;");
        file.AppendLine();
        file.AppendLine(Template(m).TrimEnd());
        foreach (var kernel in m.Kernels)
        {
            file.AppendLine();
            file.AppendLine($"fn kernel_{kernel.Suffix.ToLowerInvariant()}(x: u64, y: u64) -> u64 {{");
            Statements(file, kernel.Body, 1);
            file.AppendLine("}");
        }
        file.AppendLine();
        file.AppendLine("pub fn mix(x: u64) -> u64 {");
        file.AppendLine($"    {MixBody(m, k => "kernel_" + k.ToLowerInvariant(), Literal)}");
        file.AppendLine("}");
        file.AppendLine();
        file.AppendLine("pub fn run(seed: u64) -> u64 {");
        bool mutable = m.Dependencies.Count > 0 || m.Editable;
        file.AppendLine($"    let {(mutable ? "mut " : "")}r = {Entry(m.Kind)}(seed ^ {Literal(m.Salt)});");
        foreach (var d in m.Dependencies)
            file.AppendLine($"    r ^= {ModulePath(d.Module)}::mix(r.wrapping_add({Literal(d.Offset)}));");
        if (m.Editable)
            file.AppendLine("    r ^= 0; // bench:edit");
        file.AppendLine("    mix(r)");
        file.AppendLine("}");
        return file.ToString();
    }

    static string Entry(Kind kind) => kind switch
    {
        Kind.Vector => "simulate",
        Kind.Machine => "scan",
        Kind.Dispatch => "dispatch",
        Kind.Tally => "tally",
        Kind.Sorter => "sort_and_search",
        Kind.Ring => "churn",
        Kind.Checksum => "checksum",
        Kind.Text => "render",
        Kind.Matrix => "power",
        Kind.Forest => "connect",
        _ => throw new ArgumentOutOfRangeException(nameof(kind)),
    };

    string Template(ModuleSpec m) => m.Kind switch
    {
        Kind.Vector => $$"""
            #[derive(Clone, Copy)]
            struct Vec3 {
                x: u64,
                y: u64,
                z: u64,
            }

            impl Vec3 {
                fn new(x: u64, y: u64, z: u64) -> Self {
                    Vec3 { x, y, z }
                }

                fn add(self, other: Vec3) -> Vec3 {
                    Vec3::new(self.x.wrapping_add(other.x), self.y.wrapping_add(other.y), self.z.wrapping_add(other.z))
                }

                fn scale(self, factor: u64) -> Vec3 {
                    Vec3::new(self.x.wrapping_mul(factor), self.y.wrapping_mul(factor), self.z.wrapping_mul(factor))
                }

                fn dot(self, other: Vec3) -> u64 {
                    self.x
                        .wrapping_mul(other.x)
                        .wrapping_add(self.y.wrapping_mul(other.y))
                        .wrapping_add(self.z.wrapping_mul(other.z))
                }

                fn cross(self, other: Vec3) -> Vec3 {
                    Vec3::new(
                        self.y.wrapping_mul(other.z).wrapping_sub(self.z.wrapping_mul(other.y)),
                        self.z.wrapping_mul(other.x).wrapping_sub(self.x.wrapping_mul(other.z)),
                        self.x.wrapping_mul(other.y).wrapping_sub(self.y.wrapping_mul(other.x)),
                    )
                }
            }

            fn simulate(seed: u64) -> u64 {
                let mut rng = Rng::new(seed);
                let mut sum = Vec3::new(0, 0, 0);
                for _ in 0..{{m.Count}} {
                    let x = rng.next();
                    let y = rng.next();
                    let z = rng.next();
                    let v = Vec3::new(x, y, z);
                    let w = v.cross(sum).add(v.scale({{Literal(m.Multiplier)}}));
                    sum = sum.add(w);
                    if sum.dot(v) & 1 == 1 {
                        sum = sum.scale({{Literal(m.Constant)}});
                    }
                }
                sum.dot(sum) ^ sum.x
            }
            """,
        Kind.Machine => $$"""
            #[derive(Clone, Copy)]
            enum State {
                Idle,
                Number,
                Word,
                Space,
                Done,
            }

            fn step(state: State, c: u64) -> State {
                match state {
                    State::Idle => {
                        if c < 48 {
                            State::Space
                        } else if c < 58 {
                            State::Number
                        } else {
                            State::Word
                        }
                    }
                    State::Number => {
                        if (48..58).contains(&c) {
                            State::Number
                        } else if c == 0 {
                            State::Done
                        } else {
                            State::Space
                        }
                    }
                    State::Word => {
                        if c >= 58 {
                            State::Word
                        } else if c < 48 {
                            State::Space
                        } else {
                            State::Number
                        }
                    }
                    State::Space => {
                        if c < 48 {
                            State::Space
                        } else {
                            State::Idle
                        }
                    }
                    State::Done => State::Done,
                }
            }

            fn scan(seed: u64) -> u64 {
                let mut rng = Rng::new(seed);
                let mut state = State::Idle;
                let mut numbers = 0u64;
                let mut words = 0u64;
                let mut spaces = 0u64;
                let mut acc: u64 = {{Literal(m.Constant)}};
                for i in 0..{{m.Count}}u64 {
                    let c = rng.next() >> 56;
                    state = step(state, c);
                    match state {
                        State::Number => {
                            numbers += 1;
                            acc = acc.wrapping_mul(31).wrapping_add(c);
                        }
                        State::Word => {
                            words += 1;
                            acc = rotl(acc, 5) ^ c;
                        }
                        State::Space => spaces += 1,
                        State::Idle => acc = acc.wrapping_add(i),
                        State::Done => {
                            state = State::Idle;
                            acc ^= {{Literal(m.Constant2)}};
                        }
                    }
                }
                acc ^ (numbers << 40) ^ (words << 20) ^ spaces
            }
            """,
        Kind.Dispatch => $$"""
            trait Transform {
                fn apply(&self, value: u64) -> u64;
                fn weight(&self) -> u64;
            }

            struct Rotate {
                amount: u32,
                bias: u64,
            }

            impl Transform for Rotate {
                fn apply(&self, value: u64) -> u64 {
                    rotl(value, self.amount) ^ self.bias
                }

                fn weight(&self) -> u64 {
                    u64::from(self.amount)
                }
            }

            struct Affine {
                multiplier: u64,
                offset: u64,
            }

            impl Transform for Affine {
                fn apply(&self, value: u64) -> u64 {
                    value.wrapping_mul(self.multiplier).wrapping_add(self.offset)
                }

                fn weight(&self) -> u64 {
                    self.multiplier
                }
            }

            struct Fold {
                mask: u64,
            }

            impl Transform for Fold {
                fn apply(&self, value: u64) -> u64 {
                    (value ^ (value >> 29)).wrapping_add(value & self.mask)
                }

                fn weight(&self) -> u64 {
                    self.mask >> 32
                }
            }

            fn drive(transform: &dyn Transform, start: u64, steps: u64) -> u64 {
                let mut value = start;
                for i in 0..steps {
                    value = transform.apply(value).wrapping_add(i);
                }
                value ^ transform.weight()
            }

            fn dispatch(seed: u64) -> u64 {
                let mut rng = Rng::new(seed);
                let rotate = Rotate { amount: {{m.Shift}}, bias: {{Literal(m.Constant)}} };
                let affine = Affine { multiplier: {{Literal(m.Multiplier)}}, offset: {{Literal(m.Constant2)}} };
                let fold = Fold { mask: {{Literal(m.Mask)}} };
                let mut value = rng.next();
                for _ in 0..{{m.Count}} {
                    let pick = rng.next() % 3;
                    value = if pick == 0 {
                        drive(&rotate, value, {{m.Inner}})
                    } else if pick == 1 {
                        drive(&affine, value, {{m.Inner}})
                    } else {
                        drive(&fold, value, {{m.Inner}})
                    };
                }
                value
            }
            """,
        Kind.Tally => $$"""
            fn tally(seed: u64) -> u64 {
                let mut rng = Rng::new(seed);
                let mut counts: HashMap<u64, u64> = HashMap::new();
                for i in 0..{{m.Count}}u64 {
                    let key = rng.next() % {{m.Size}};
                    *counts.entry(key).or_insert(0) += i + 1;
                }
                let mut acc: u64 = {{Literal(m.Constant)}};
                for key in 0..{{m.Size}}u64 {
                    if let Some(&count) = counts.get(&key) {
                        acc = fnv(acc, count) ^ key;
                    }
                }
                acc ^ counts.len() as u64
            }
            """,
        Kind.Sorter => $$"""
            fn insertion_sort(values: &mut [u64]) {
                for i in 1..values.len() {
                    let value = values[i];
                    let mut j = i;
                    while j > 0 && values[j - 1] > value {
                        values[j] = values[j - 1];
                        j -= 1;
                    }
                    values[j] = value;
                }
            }

            fn lower_bound(values: &[u64], target: u64) -> usize {
                let mut low = 0;
                let mut high = values.len();
                while low < high {
                    let middle = low + (high - low) / 2;
                    if values[middle] < target {
                        low = middle + 1;
                    } else {
                        high = middle;
                    }
                }
                low
            }

            fn sort_and_search(seed: u64) -> u64 {
                let mut rng = Rng::new(seed);
                let mut values = [0u64; {{m.Count}}];
                for value in values.iter_mut() {
                    *value = rng.next() >> 2;
                }
                insertion_sort(&mut values);
                let mut acc = 0u64;
                for _ in 0..{{m.Size}} {
                    let target = rng.next() >> 2;
                    acc = acc.wrapping_mul({{Literal(m.Multiplier)}}).wrapping_add(lower_bound(&values, target) as u64);
                }
                acc ^ values[{{m.Count / 2}}]
            }
            """,
        Kind.Ring => $$"""
            const CAPACITY: usize = {{m.Size}};

            struct Ring {
                items: [u64; CAPACITY],
                head: usize,
                count: usize,
            }

            impl Ring {
                fn new() -> Self {
                    Ring { items: [0; CAPACITY], head: 0, count: 0 }
                }

                fn push(&mut self, value: u64) {
                    self.items[(self.head + self.count) % CAPACITY] = value;
                    if self.count < CAPACITY {
                        self.count += 1;
                    } else {
                        self.head = (self.head + 1) % CAPACITY;
                    }
                }

                fn pop(&mut self) -> u64 {
                    if self.count == 0 {
                        return 0;
                    }
                    let value = self.items[self.head];
                    self.head = (self.head + 1) % CAPACITY;
                    self.count -= 1;
                    value
                }

                fn weighted_sum(&self) -> u64 {
                    let mut sum = 0u64;
                    for i in 0..self.count {
                        sum = sum.wrapping_add(self.items[(self.head + i) % CAPACITY].wrapping_mul(i as u64 + 1));
                    }
                    sum
                }
            }

            fn churn(seed: u64) -> u64 {
                let mut rng = Rng::new(seed);
                let mut ring = Ring::new();
                let mut acc = 0u64;
                for _ in 0..{{m.Count}} {
                    let value = rng.next();
                    if value & 3 == 0 {
                        acc ^= ring.pop();
                    } else {
                        ring.push(value ^ acc);
                    }
                }
                acc ^ ring.weighted_sum() ^ ring.count as u64
            }
            """,
        Kind.Checksum => $$"""
            fn fill_table(table: &mut [u64; 256]) {
                for (i, entry) in table.iter_mut().enumerate() {
                    let mut crc = i as u64;
                    for _ in 0..8 {
                        crc = if crc & 1 == 1 { (crc >> 1) ^ {{Literal(m.Constant2)}} } else { crc >> 1 };
                    }
                    *entry = crc;
                }
            }

            fn update(table: &[u64; 256], crc: u64, value: u64) -> u64 {
                table[((crc ^ value) & 255) as usize] ^ (crc >> 8)
            }

            fn checksum(seed: u64) -> u64 {
                let mut rng = Rng::new(seed);
                let mut table = [0u64; 256];
                fill_table(&mut table);
                let mut crc = u64::MAX;
                for _ in 0..{{m.Count}} {
                    crc = update(&table, crc, rng.next() >> 56);
                }
                !crc ^ rotl(crc, {{m.Shift}})
            }
            """,
        Kind.Text => $$"""
            fn append_decimal(buffer: &mut Vec<u8>, value: u64) {
                if value == 0 {
                    buffer.push(b'0');
                    return;
                }
                let mut digits = [0u8; 20];
                let mut count = 0;
                let mut rest = value;
                while rest > 0 {
                    digits[count] = b'0' + (rest % 10) as u8;
                    rest /= 10;
                    count += 1;
                }
                while count > 0 {
                    count -= 1;
                    buffer.push(digits[count]);
                }
            }

            fn render(seed: u64) -> u64 {
                let mut rng = Rng::new(seed);
                let mut buffer = Vec::new();
                for _ in 0..{{m.Count}} {
                    append_decimal(&mut buffer, rng.next() % {{m.Size}});
                    buffer.push(b',');
                }
                let mut total = 0u64;
                let mut current = 0u64;
                let mut fields = 0u64;
                for &byte in &buffer {
                    if byte == b',' {
                        total = total.wrapping_mul({{m.Multiplier}}).wrapping_add(current);
                        current = 0;
                        fields += 1;
                    } else {
                        current = current * 10 + u64::from(byte - b'0');
                    }
                }
                total ^ (fields << 32) ^ buffer.len() as u64
            }
            """,
        Kind.Matrix => $$"""
            const SIZE: usize = {{m.Size}};
            const CELLS: usize = SIZE * SIZE;

            #[derive(Clone, Copy)]
            struct Matrix {
                cells: [u64; CELLS],
            }

            impl Matrix {
                fn zero() -> Self {
                    Matrix { cells: [0; CELLS] }
                }

                fn identity() -> Self {
                    let mut result = Matrix::zero();
                    for i in 0..SIZE {
                        result.cells[i * SIZE + i] = 1;
                    }
                    result
                }

                fn multiply(&self, other: &Matrix) -> Matrix {
                    let mut result = Matrix::zero();
                    for row in 0..SIZE {
                        for column in 0..SIZE {
                            let mut sum = 0u64;
                            for k in 0..SIZE {
                                sum = sum.wrapping_add(self.cells[row * SIZE + k].wrapping_mul(other.cells[k * SIZE + column]));
                            }
                            result.cells[row * SIZE + column] = sum;
                        }
                    }
                    result
                }

                fn trace(&self) -> u64 {
                    let mut sum = 0u64;
                    for i in 0..SIZE {
                        sum = sum.wrapping_add(self.cells[i * SIZE + i]);
                    }
                    sum
                }
            }

            fn power(seed: u64) -> u64 {
                let mut rng = Rng::new(seed);
                let mut base = Matrix::zero();
                for cell in base.cells.iter_mut() {
                    *cell = rng.next();
                }
                let mut result = Matrix::identity();
                for step in 0..{{m.Count}} {
                    result = result.multiply(&base);
                    base.cells[step % CELLS] ^= result.cells[0];
                }
                result.trace() ^ result.cells[CELLS - 1]
            }
            """,
        Kind.Forest => $$"""
            const NODES: usize = {{m.Size}};

            struct Forest {
                parent: [usize; NODES],
                rank: [u32; NODES],
            }

            impl Forest {
                fn new() -> Self {
                    let mut parent = [0; NODES];
                    for (i, entry) in parent.iter_mut().enumerate() {
                        *entry = i;
                    }
                    Forest { parent, rank: [0; NODES] }
                }

                fn find(&mut self, node: usize) -> usize {
                    let mut root = node;
                    while self.parent[root] != root {
                        self.parent[root] = self.parent[self.parent[root]];
                        root = self.parent[root];
                    }
                    root
                }

                fn unite(&mut self, a: usize, b: usize) -> bool {
                    let mut root_a = self.find(a);
                    let mut root_b = self.find(b);
                    if root_a == root_b {
                        return false;
                    }
                    if self.rank[root_a] < self.rank[root_b] {
                        std::mem::swap(&mut root_a, &mut root_b);
                    }
                    self.parent[root_b] = root_a;
                    if self.rank[root_a] == self.rank[root_b] {
                        self.rank[root_a] += 1;
                    }
                    true
                }
            }

            fn connect(seed: u64) -> u64 {
                let mut rng = Rng::new(seed);
                let mut forest = Forest::new();
                let mut merges = 0u64;
                for _ in 0..{{m.Inner}} {
                    let a = (rng.next() % NODES as u64) as usize;
                    let b = (rng.next() % NODES as u64) as usize;
                    if forest.unite(a, b) {
                        merges += 1;
                    }
                }
                let mut acc = 0u64;
                for i in 0..NODES {
                    acc = acc.wrapping_mul(31).wrapping_add(forest.find(i) as u64);
                }
                acc ^ merges
            }
            """,
        _ => throw new ArgumentOutOfRangeException(nameof(m)),
    };
}
