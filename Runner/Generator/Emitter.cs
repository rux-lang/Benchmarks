using System.Text;

namespace Runner.Generator;

/// <summary>A generated source file, by its path relative to the language folder.</summary>
sealed record SourceFile(string Path, string Content);

/// <summary>
/// Writes one project in one language. The base class prints kernels from the shared syntax tree
/// through a handful of per-language hooks; each language writes its own templates.
/// </summary>
abstract class Emitter
{
    /// <summary>The language folder under Projects/&lt;Project&gt;/, as in Apps/&lt;App&gt;/.</summary>
    public abstract string Folder { get; }
    public abstract IEnumerable<SourceFile> Emit(ProjectSpec project);

    protected virtual string IndentUnit => "    ";
    protected const string Banner = "Generated by `dotnet run --project Runner -c Release -- generate`; change the generator, not this file.";

    public static readonly IReadOnlyList<Emitter> All =
        [new RuxEmitter(), new RustEmitter(), new CppEmitter(), new GoEmitter(), new CSharpEmitter(), new JavaEmitter()];

    // ------------------------------------------------------------------ expressions

    protected abstract string Literal(ulong value);
    protected abstract string Rotl(string value, int amount);
    protected virtual string ShiftRight => ">>";
    protected virtual string Mod(string value, ulong divisor) => $"{value} % {Literal(divisor)}";
    protected virtual string BinaryText(Binary b) => $"{Operand(b.Left, true)} {b.Op} {Operand(b.Right, true)}";

    protected string Expression(Expr e) => e switch
    {
        Var v => v.Name,
        Lit l => Literal(l.Value),
        Binary b => BinaryText(b),
        ShiftBy s => $"{Operand(s.Value, true)} {(s.Left ? "<<" : ShiftRight)} {s.Amount}",
        Rotate r => Rotl(Expression(r.Value), r.Amount),
        Modulo m => Mod(Operand(m.Value, true), m.Divisor),
        _ => throw new ArgumentOutOfRangeException(nameof(e)),
    };

    /// <summary>Operators nest in parentheses rather than relying on each language's precedence.</summary>
    protected string Operand(Expr e, bool parenthesize) =>
        parenthesize && e is Binary or ShiftBy or Modulo && !(e is Modulo && ModIsCall) ? $"({Expression(e)})" : Expression(e);

    protected virtual bool ModIsCall => false;

    protected virtual string Condition(Compare c) =>
        $"({Operand(c.Value, true)} & {Literal(c.Mask)}) {c.Op} {Literal(c.Limit)}";

    // ------------------------------------------------------------------ statements

    protected abstract string Declare(Declare d);
    protected virtual string Assign(Assign a) => $"{a.Name} = {Expression(a.Value)};";
    /// <summary>Block heads are written without their opening brace; <see cref="AllmanBraces"/> decides where it goes.</summary>
    protected virtual string IfHead(Compare c) => $"if ({Condition(c)})";
    protected virtual bool AllmanBraces => false;
    protected abstract string LoopHead(Loop loop, bool variableUsed);
    protected virtual string ReturnLine(Return r, bool last) => $"return {Expression(r.Value)};";

    protected void Statements(StringBuilder text, IReadOnlyList<Stmt> body, int depth)
    {
        string pad = string.Concat(Enumerable.Repeat(IndentUnit, depth));
        for (int i = 0; i < body.Count; i++)
        {
            switch (body[i])
            {
                case Declare d:
                    text.Append(pad).AppendLine(Declare(d));
                    break;
                case Assign a:
                    text.Append(pad).AppendLine(Assign(a));
                    break;
                case If s:
                    Open(text, pad, IfHead(s.Condition));
                    Statements(text, s.Then, depth + 1);
                    if (AllmanBraces)
                        text.Append(pad).AppendLine("}").Append(pad).AppendLine("else").Append(pad).AppendLine("{");
                    else
                        text.Append(pad).AppendLine("} else {");
                    Statements(text, s.Else, depth + 1);
                    text.Append(pad).AppendLine("}");
                    break;
                case Loop l:
                    Open(text, pad, LoopHead(l, Kernel.Mentions(l.Body, l.Variable)));
                    Statements(text, l.Body, depth + 1);
                    text.Append(pad).AppendLine("}");
                    break;
                case Return r:
                    text.Append(pad).AppendLine(ReturnLine(r, i == body.Count - 1));
                    break;
            }
        }
    }

    void Open(StringBuilder text, string pad, string head)
    {
        if (AllmanBraces)
            text.Append(pad).AppendLine(head).Append(pad).AppendLine("{");
        else
            text.Append(pad).Append(head).AppendLine(" {");
    }

    // ------------------------------------------------------------------ helpers

    /// <summary>Hexadecimal for wide constants, decimal for small ones.</summary>
    protected static string Number(ulong value) => value < 1 << 20 ? value.ToString() : $"0x{value:X}";

    protected string Indent(string text, int depth)
    {
        string pad = string.Concat(Enumerable.Repeat(IndentUnit, depth));
        return string.Join("\n", text.Replace("\r\n", "\n").Split('\n').Select(l => l.Length == 0 ? l : pad + l));
    }

    protected static string Lower(string name) => char.ToLowerInvariant(name[0]) + name[1..];

    /// <summary>The kernel names in call order: Mix nests them so each one is used.</summary>
    protected static string MixBody(ModuleSpec m, Func<string, string> kernel, Func<ulong, string> literal, string x = "x")
    {
        string a = $"{kernel("A")}({x}, {literal(m.MixKey1)})";
        return m.Kernels.Count == 2
            ? $"{kernel("B")}({a}, {x} ^ {literal(m.MixKey2)})"
            : $"{kernel("C")}({a}, {kernel("B")}({x} ^ {literal(m.MixKey2)}, {x}))";
    }

    protected static string Comment(string prefix, ModuleSpec m) =>
        $"{prefix} {m.Name}: {m.Description}\n{prefix} {Banner}\n";

    /// <summary>The comment at the top of a source file: the module it holds, or the range of modules.</summary>
    protected static string FileComment(string prefix, IReadOnlyList<ModuleSpec> modules) => modules.Count == 1
        ? Comment(prefix, modules[0])
        : $"{prefix} {modules[0].File}: modules {modules[0].Name} to {modules[^1].Name}.\n{prefix} {Banner}\n";

    /// <summary>The comment above one module in a file of several (none when the file holds one).</summary>
    protected static string ModuleComment(string prefix, ModuleSpec m, string indent = "") =>
        m.SharesFile ? $"{indent}{prefix} {m.Name}: {m.Description}\n" : "";

    /// <summary>The source file, relative to the language folder, that holds the module (the one `compile` edits).</summary>
    public abstract string ModuleFile(ModuleSpec m);
}
